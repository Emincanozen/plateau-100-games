/** Lettres de l'alphabet utilisees par les jeux de lettres. */
export const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'.split('');

/** Retire accents et signes pour comparer un mot saisi a un mot de la liste. */
export function normaliser(mot: string): string {
  return mot
    .toUpperCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^A-Z]/g, '');
}

